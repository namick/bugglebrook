import type { Advert, ItemDef, ItemShape, MaterialId, ItemArt, ToyKind } from './types';
import { POTIONS } from './potions';

const EAT_FOOD: Advert = { action: 'eat', needs: { need_hunger: 20 } };

interface Spec {
  name: string;
  shape: ItemShape;
  material: MaterialId;
  density: number;
  friction?: number;
  restitution?: number;
  art: ItemArt;
  color: number;
  accent: number;
  tags?: readonly string[];
  adverts?: readonly Advert[];
}

/** An item with the usual physics for its material unless the spec says otherwise. */
function item(id: string, spec: Spec, extra: Partial<ItemDef> = {}): ItemDef {
  return {
    id,
    name: spec.name,
    shape: spec.shape,
    material: spec.material,
    density: spec.density,
    friction: spec.friction ?? 0.6,
    restitution: spec.restitution ?? 0.2,
    art: spec.art,
    color: spec.color,
    accent: spec.accent,
    tags: spec.tags ?? [],
    adverts: spec.adverts ?? [],
    ...extra,
  };
}

const box = (width: number, height: number): ItemShape => ({ type: 'box', width, height });
const circle = (radius: number): ItemShape => ({ type: 'circle', radius });
const toy = (kind: ToyKind): Partial<ItemDef> => ({ toy: kind });

