import type { ItemDef, ItemShape } from './types';

const box = (width: number, height: number): ItemShape => ({ type: 'box', width, height });

/** A map scrap: four of them, torn from one map (game design doc, section 12). */
function scrap(n: number, color: number): ItemDef {
  return {
    id: `item_map_scrap_${n}`,
    name: 'Map scrap',
    shape: box(0.56, 0.44),
    material: 'mat_paper',
    density: 0.35,
    friction: 0.7,
    restitution: 0.05,
    art: 'map_scrap',
    color: 0xf2dfb0,
    accent: color,
    tags: ['tag_light'],
    adverts: [],
    unique: true,
  };
}

